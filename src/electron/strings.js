/** Map an OS locale (e.g. `de-AT`, `zh_Hans`) to a supported dictionary. */
function resolveLocale(locale) {
  const raw = String(locale || 'en').replace('_', '-');
  if (MESSAGES[raw]) return raw;
  const language = raw.split('-')[0];
  if (MESSAGES[language]) return language;
  if (language === 'zh') return 'zh-CN';
  return 'en';
}

/** Translate `key`, interpolating `{{name}}` placeholders. */
function translate(locale, key, replacements = {}) {
  const dictionary = MESSAGES[resolveLocale(locale)] || MESSAGES.en;
  const template = dictionary[key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_match, name) =>
    replacements[name] === undefined ? `{{${name}}}` : String(replacements[name]),
  );
}

module.exports = { MESSAGES, resolveLocale, translate };
